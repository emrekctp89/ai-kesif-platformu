export function formatPitchDeckArtifact(run, locale = 'tr') {
  if (!run) return '';
  const slides = (run.slides || [])
    .map((s, i) => {
      const bullets = (s.bullets || []).map((b) => `  - ${b}`).join('\n');
      return `### ${i + 1}. ${s.title}\n${bullets}`;
    })
    .join('\n\n');
  const visuals = (run.visualPrompts || []).map((p, i) => `${i + 1}. ${p}`).join('\n');
  const notes = (run.speakerNotes || []).map((n, i) => `${i + 1}. ${n}`).join('\n');

  if (locale === 'en') {
    return `# Pitch deck pack

## Narrative
${run.narrative || ''}

## Slides
${slides}

## Visual prompts
${visuals}

## Speaker notes
${notes}

---
Generated by aikeşif pitch-deck pack runner.`;
  }

  return `# Pitch deck paketi

## Anlatı
${run.narrative || ''}

## Slaytlar
${slides}

## Görsel promptlar
${visuals}

## Sunum notları
${notes}

---
aikeşif pitch-deck pack runner çıktısı.`;
}

export async function runPitchDeckPack(brief, locale = 'tr') {
  if (!getJobPackById('pitch-deck', locale)) throw new Error('unknown_pack');

  const lang = locale === 'en' ? 'English' : 'Turkish';
  const prompt = `You are a pitch deck pack runner for an AI tools platform.
User brief: ${String(brief || '').slice(0, 500)}
Respond ONLY with valid JSON; user-facing strings in ${lang}:
{
  "narrative": "one paragraph investor narrative",
  "slides": [{ "title": "Problem", "bullets": ["...","..."] }],
  "visualPrompts": ["prompt1","prompt2"],
  "speakerNotes": ["note1","note2"]
}
Aim for 7-10 slides.`;

  const { data: parsed, source: llmSource } = await callProviderJson(prompt);
  if (!parsed || !Array.isArray(parsed.slides) || parsed.slides.length < 5) {
    return { ...buildLocalPitchDeckRun(brief, locale), source: 'local' };
  }

  return {
    packId: 'pitch-deck',
    goal: 'presentation-creation',
    bridge: 'runner',
    narrative: String(parsed.narrative || '').slice(0, 800),
    slides: parsed.slides.slice(0, 12).map((s) => ({
      title: String(s.title || '').slice(0, 80),
      bullets: Array.isArray(s.bullets)
        ? s.bullets.map((b) => String(b).slice(0, 160)).slice(0, 6)
        : [],
    })),
    visualPrompts: Array.isArray(parsed.visualPrompts)
      ? parsed.visualPrompts.map((p) => String(p).slice(0, 400)).slice(0, 4)
      : [],
    speakerNotes: Array.isArray(parsed.speakerNotes)
      ? parsed.speakerNotes.map((n) => String(n).slice(0, 200)).slice(0, 8)
      : [],
    source: llmSource || 'provider',
  };
}

